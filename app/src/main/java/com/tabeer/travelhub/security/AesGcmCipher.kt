package com.tabeer.travelhub.security

import javax.crypto.Cipher
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Supplies the AES key. In production this is a non-exportable Android Keystore key. */
interface KeyProvider {
    fun getKey(): SecretKey
}

/** Thrown for any encryption/decryption failure. Messages never contain plaintext or key material. */
class CryptoException(message: String) : Exception(message)

/**
 * Standard AES-256-GCM (authenticated encryption) — no custom cryptography.
 * Output layout: 12-byte random IV || ciphertext+16-byte tag.
 * The IV is generated by the Cipher itself (required by Android Keystore, which refuses
 * caller-supplied IVs for encryption), so it is unique per encryption.
 * [aad] binds the ciphertext to its record id so blobs cannot be swapped between portals.
 */
class AesGcmCipher(private val keys: KeyProvider) {
    fun encrypt(plain: ByteArray, aad: ByteArray): ByteArray = try {
        val c = Cipher.getInstance(TRANSFORM)
        c.init(Cipher.ENCRYPT_MODE, keys.getKey())
        c.updateAAD(aad)
        c.iv + c.doFinal(plain)
    } catch (e: Exception) {
        throw CryptoException("Encryption failed")
    }

    fun decrypt(blob: ByteArray, aad: ByteArray): ByteArray {
        if (blob.size < IV_BYTES + TAG_BYTES) throw CryptoException("Invalid encrypted data")
        return try {
            val c = Cipher.getInstance(TRANSFORM)
            c.init(Cipher.DECRYPT_MODE, keys.getKey(), GCMParameterSpec(TAG_BITS, blob.copyOfRange(0, IV_BYTES)))
            c.updateAAD(aad)
            c.doFinal(blob, IV_BYTES, blob.size - IV_BYTES)
        } catch (e: Exception) {
            throw CryptoException("Decryption failed")
        }
    }

    companion object {
        private const val TRANSFORM = "AES/GCM/NoPadding"
        private const val IV_BYTES = 12
        private const val TAG_BITS = 128
        private const val TAG_BYTES = 16
    }
}
